import fs from 'node:fs';
import rockauto from '../src/lib/rockauto.js';

/**
 * Collect every catalogue term (groups + part types) for a set of cars.
 *
 * RockAuto has no public index of part types, so they are read from the
 * catalogue of a handful of diverse cars. The names repeat heavily
 * across models; anything missed still registers itself the first time
 * a driver opens it.
 *
 * Writes:
 *   src/lib/locales/parts-keys.js      - the English keys, for the app
 *   data/parts-translation-keys.json   - the same keys, value empty
 */

const CARS = [
  ['HONDA', '1999', 'CIVIC'],
  ['TOYOTA', '2010', 'CAMRY'],
  ['FORD', '2015', 'F-150'],
  ['BMW', '2008', '328I'],
  ['VOLKSWAGEN', '2005', 'GOLF'],
  ['MERCEDES-BENZ', '2010', 'C300'],
  ['SUBARU', '2015', 'OUTBACK'],
  ['TESLA', '2020', 'MODEL 3'],
];

const log = (...args) => console.log(new Date().toISOString().slice(11, 19), ...args);
const groups = new Set();
const types = new Set();

for (const [make, year, model] of CARS) {
  try {
    const engines = await rockauto.engines(make, year, model);
    if (!engines.length) {
      log('no engines:', make, year, model);
      continue;
    }
    const car = { make, year, model, engine: engines[0].name, carcode: String(engines[0].id) };
    const list = await rockauto.groups(make, year, model, car.engine, car.carcode);
    log(make, year, model, 'groups:', list.length);
    for (const group of list) {
      groups.add(group.name);
      try {
        const found = await rockauto.partTypes({ ...car, group: group.name });
        for (const row of found) types.add(row.name);
        log('  ', group.name, found.length);
      } catch (error) {
        log('   failed', group.name, '-', error.message);
      }
    }
  } catch (error) {
    log('failed car:', make, year, model, '-', error.message);
  }
}

const keys = [...new Set([...groups, ...types])].sort((a, b) => a.localeCompare(b));
log('TOTAL groups:', groups.size, 'types:', types.size, 'unique keys:', keys.length);

const header = `/**
 * English catalogue terms (RockAuto groups and part types).
 *
 * Generated by scripts/parts-keys.mjs. They are shipped to the
 * translation table as keys with no Georgian text, so they show up in
 * Admin -> Translations ready to be translated. Anything not listed
 * here still registers itself when a driver opens that part type.
 */
`;
fs.writeFileSync('src/lib/locales/parts-keys.js', `${header}export const PART_KEYS = ${JSON.stringify(keys, null, 2)};\n\nexport default PART_KEYS;\n`, 'utf8');
fs.writeFileSync('data/parts-translation-keys.json', `${JSON.stringify(Object.fromEntries(keys.map((key) => [key, ''])), null, 2)}\n`, 'utf8');
log('wrote src/lib/locales/parts-keys.js and data/parts-translation-keys.json');
